from typing import Dict, Any, List, Optional, Tuple
from enum import Enum
from dataclasses import dataclass
import re

class ClaimType(str, Enum):
    OBSERVED = "observed"
    DETERMINISTIC = "deterministic"
    INFERRED = "inferred"
    UNKNOWN = "unknown"

@dataclass
class GroundedClaim:
    claim: str
    claim_type: ClaimType
    evidence_refs: List[str]
    confidence: float

@dataclass
class GroundedResponse:
    claims: List[GroundedClaim]
    overall_confidence: float
    warnings: List[str]
    is_grounded: bool
    safe_response: Optional[Dict[str, Any]] = None

class GroundingValidator:
    """Validate AI responses against evidence and enforce anti-hallucination guardrails"""

    def __init__(self):
        self.prohibited_phrases = self._load_prohibited_phrases()
        self.required_qualifiers = self._load_required_qualifiers()

    def _load_prohibited_phrases(self) -> List[str]:
        """Phrases that represent unconfirmed active breach or attacker exploitation"""
        return [
            'attacker',
            'compromised',
            'breached',
            'hacked',
            'exploited',
            'active exploitation',
            'malware',
            'ransomware',
            'data theft',
            'stolen credentials',
            'confirmed exploitation',
            'system is pwned'
        ]

    def _load_required_qualifiers(self) -> List[str]:
        """Qualifiers that must accompany impact or inferential claims"""
        return [
            'may',
            'could',
            'potentially',
            'depending',
            'if',
            'can',
            'might',
            'possible'
        ]

    def validate_response(self, response: Dict[str, Any], evidence: Dict[str, Any]) -> GroundedResponse:
        """Validate AI response against evidence; detects and blocks hallucinations"""
        claims: List[GroundedClaim] = []
        warnings: List[str] = []
        has_critical_hallucination = False

        evidence_str = str(evidence or {}).lower()

        # Extract all text segments generated by LLM
        extracted = self._extract_claims(response)

        for claim in extracted:
            text = claim['text']
            text_lower = text.lower()
            evidence_refs = self._find_evidence_refs(text_lower, evidence)

            # Check for prohibited breach claims that are NOT in evidence
            for phrase in self.prohibited_phrases:
                if phrase in text_lower:
                    if phrase not in evidence_str:
                        warnings.append(f"Hallucination detected: ungrounded claim of '{phrase}' in '{text}'")
                        has_critical_hallucination = True

            # Classify claim
            claim_type, confidence = self._classify_claim(text_lower, evidence_refs, claim.get('source'))
            claims.append(GroundedClaim(
                claim=text,
                claim_type=claim_type,
                evidence_refs=evidence_refs,
                confidence=confidence
            ))

        is_grounded = not has_critical_hallucination and len(warnings) == 0
        overall_conf = (sum(c.confidence for c in claims) / len(claims)) if claims else 0.5

        safe_res = None
        if not is_grounded:
            safe_res = {
                "summary": "Potential misconfiguration detected. Detailed impact requires further telemetry verification.",
                "observed": response.get("observed", ["Resource misconfiguration identified based on static rule evaluation."]),
                "inferred": ["Configuration deviation may increase exposure to automated threat scanning."],
                "unknown": ["Whether active exploitation or credential compromise has occurred."],
                "recommendations": response.get("recommendations", ["Review access control and enforce least privilege."]),
                "citations": response.get("citations", []),
                "confidence_score": 0.50,
                "guardrail_intercepted": True,
                "warnings": warnings
            }

        return GroundedResponse(
            claims=claims,
            overall_confidence=overall_conf if is_grounded else 0.50,
            warnings=warnings,
            is_grounded=is_grounded,
            safe_response=safe_res
        )

    def _extract_claims(self, response: Dict[str, Any]) -> List[Dict[str, str]]:
        claims = []
        if 'summary' in response and response['summary']:
            claims.append({'text': str(response['summary']), 'source': 'summary'})

        for field in ('observed', 'inferred', 'unknown', 'recommendations'):
            items = response.get(field, [])
            if isinstance(items, list):
                for item in items:
                    if item:
                        claims.append({'text': str(item), 'source': field})
            elif isinstance(items, str):
                claims.append({'text': items, 'source': field})

        return claims

    def _find_evidence_refs(self, text_lower: str, evidence: Dict[str, Any]) -> List[str]:
        refs = []
        for k, v in (evidence or {}).items():
            if str(v).lower() in text_lower:
                refs.append(f"evidence.{k}")
        return refs

    def _classify_claim(self, text_lower: str, evidence_refs: List[str], source: Optional[str]) -> Tuple[ClaimType, float]:
        if source == "observed" or evidence_refs:
            return ClaimType.OBSERVED, 0.95
        if source == "unknown":
            return ClaimType.UNKNOWN, 0.90
        if any(w in text_lower for w in ['may', 'could', 'potentially', 'risk', 'possible']):
            return ClaimType.INFERRED, 0.80
        return ClaimType.INFERRED, 0.70
